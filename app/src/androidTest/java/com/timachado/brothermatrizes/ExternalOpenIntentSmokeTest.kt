    @get:Rule
    val composeRule =
        createEmptyComposeRule()

    @Test
    fun actionViewOpensPesDirectlyInViewer() {
        val context =
            InstrumentationRegistry
                .getInstrumentation()
                .targetContext

        val sharedDir =
            File(
                context.cacheDir,
                "shared"
            ).apply {
                mkdirs()
            }

        val matrixFile =
            File(
                sharedDir,
                "random1.pes"
            )

        matrixFile.writeBytes(
            Base64.decode(
                SAMPLE_PES_BASE64,
                Base64.DEFAULT
            )
        )

        val uri =
            FileProvider.getUriForFile(
                context,
                context.packageName +
                    ".fileprovider",
                matrixFile
            )

        val intent =
            Intent(
                context,
                MainActivity::class.java
            ).apply {
                action =
                    Intent.ACTION_VIEW
                data =
                    uri
                addFlags(
                    Intent.FLAG_ACTIVITY_NEW_TASK or
                        Intent.FLAG_GRANT_READ_URI_PERMISSION
                )
            }

        ActivityScenario
            .launch<MainActivity>(
                intent
            )
            .use {
                composeRule.waitUntil(
                    timeoutMillis =
                        15_000
                ) {
                    composeRule
                        .onAllNodesWithText(
                            "random1.pes"
                        )
                        .fetchSemanticsNodes()
                        .isNotEmpty()
                }

                composeRule
                    .onNodeWithText(
                        "random1.pes"
                    )
                    .assertIsDisplayed()
            }
    }

