/**
 * Reimplementation independently designed from normal embroidery geometry.
 *
 * It does NOT use MaoDesign binaries or proprietary routines. The reference
 * APK is a proprietary .NET MAUI application and contains no recorded
 * stitch-out for the user's font/name. Exact equivalence requires comparing
 * matching machine files generated by that app.
 *
 * Distinct pipeline: actual font outline -> filled binary mask -> medial axis
 * -> edge-disjoint stroke paths -> transverse satin rails -> one center-run
 * underlay (optional) -> one satin coverage -> next path / next glyph.
 *
 * There is deliberately no Maria-specific image heuristic, global scanline
 * column ordering, multi-pass per-column locking or cleanup of sub-0.4mm
 * stitches. The rendered preview and export share the same command sequence.
 */
internal object CleanRoomSatinEngine {
    internal data class V(val x: Float, val y: Float)
    internal data class Rail(val a: V, val b: V) {
        val middle: V get() = V((a.x + b.x) / 2f, (a.y + b.y) / 2f)
    }
    internal data class PlannedGlyph(
        val rails: List<List<Rail>>,
        val sampledEdges: Int,
        val duplicateRailsDiscarded: Int
    )

    private data class Cell(val x: Int, val y: Int)
    private data class Edge(val a: Int, val b: Int) {
        companion object {
            fun of(a: Int, b: Int) =
                if (a <= b) Edge(a, b) else Edge(b, a)
        }
    }
    private data class Raster(
        val width: Int, val height: Int, val step: Float,
        val left: Float, val top: Float, val mask: BooleanArray
    ) {
        fun index(x: Int, y: Int) = y * width + x
        fun inside(x: Int, y: Int) =
            x in 0 until width && y in 0 until height && mask[index(x, y)]
        fun point(index: Int): V {
            val x = index % width
            val y = index / width
            return V(left + x * step, top + y * step)
        }
    }

    /**
     * Apply non-uniform resizing to the VECTOR contours, before any satin
     * rasterization or stitch planning. Scaling finished stitches makes the
     * satin pitch grow with the font and produces broken-looking cursive
     * outlines, especially after 2x expansion on portrait frames.
     */
    internal fun scaleGlyphContours(
        glyphs: List<List<List<AndroidSkiaOutlineExtractor.Point>>>,
        widthScale: Float,
        heightScale: Float
    ): List<List<List<AndroidSkiaOutlineExtractor.Point>>> {
        require(widthScale.isFinite() && heightScale.isFinite() &&
            widthScale in 0.5f..2.5f && heightScale in 0.5f..2.5f)
        if (widthScale == 1f && heightScale == 1f) return glyphs
        return glyphs.map { glyph ->
            glyph.map { contour ->
                contour.map { point ->
                    AndroidSkiaOutlineExtractor.Point(
                        x = point.x * widthScale,
                        y = point.y * heightScale
                    )
                }
            }
        }
    }

    fun generate(
        font: ImportedFont,
        sourceText: String,
        options: TextMatrixOptions,
        filePrefix: String
    ): Result<EmbroideryDesign> = runCatching {
        val text = sourceText.trim().take(24)
        require(text.isNotBlank()) { "Digite um nome." }
        require(options.heightMm in 4f..60f) { "Altura fora de 4 a 60 mm." }
        require(options.satinDensityMm in 0.3f..1.2f) {
            "A densidade Satin deve ficar entre 0,3 e 1,2 mm."
        }
        require(options.satinPullCompensationMm in 0f..1f) {
            "Compensação de repuxo fora do intervalo."
        }
        val format = options.outputFormat.uppercase(Locale.ROOT)
        require(format in MatrixConverter.supportedFormats) {
            "Formato de matriz não suportado."
        }
        val heightUnits = options.heightMm * 10f
        // Não inserir espaçamento automático: fontes cursivas dependem
        // de encaixe e kerning para manter suas ligações entre letras.
        val spacing = options.spacingMm * 10f
        val outlines = AndroidSkiaOutlineExtractor.extract(
            font = font,
            text = text,
            targetCapHeightUnits = heightUnits,
            spacingUnits = spacing,
            rotationDegrees = options.rotationDegrees
        )
        // The final matrix shape is fixed BEFORE sampling its satin rails.
        // Pitch and maximum satin bar length therefore remain physical
        // values in millimetres instead of being stretched with the text.
        val scaledGlyphs = scaleGlyphContours(
            outlines.glyphPolygons,
            options.widthScale,
            options.heightScale
        )
        val points = mutableListOf<EmbroideryPoint>()
        val stitcher = Stitcher(points)
        var sewnGlyphs = 0
        scaledGlyphs.forEachIndexed { glyphIndex, glyph ->
            val contours = glyph.map { contour -> contour.map { V(it.x, it.y) } }
            if (contours.isEmpty()) return@forEachIndexed
            // Use a stroke-following centreline for contextual scripts.
            // Vertical scanlines make a tall M stem sew ALONG its outline
            // instead of crossing the stroke, yielding square bands and
            // partially broken loops in Bertilda. The skeleton planner
            // follows each local tangent and places satin rails normal to
            // it; detached dots and very thin strokes have dedicated
            // reconstruction in planContours. No silent fallback to the
            // defective vertical-only path for a connected script.
            val plan = planContours(
                contours,
                densityMm = options.satinDensityMm,
                pullMm = options.satinPullCompensationMm
            )
            require(plan.rails.isNotEmpty()) {
                "A fonte não produziu uma faixa Satin segura na letra " +
                    (glyphIndex + 1) + ". Ajuste a altura ou a fonte."
            }
            stitcher.sewGlyph(
                plan.rails,
                if (outlines.contextualShapingPreserved) SatinUnderlayMode.NONE
                else options.satinUnderlayMode,
                forceJumpBetweenPaths = outlines.contextualShapingPreserved
            )
            sewnGlyphs++
        }
        require(sewnGlyphs > 0 && points.any { it.command == StitchCommand.STITCH }) {
            "Não foram geradas pontadas válidas."
        }
        // A presença de pontos não é suficiente para liberar uma fonte:
        // a sequência precisa reproduzir pelo menos a silhueta do glifo.
        val silhouette = ImportedFontCoverageGuard.check(scaledGlyphs, points)
        // A script must cover more than one fifth of its vector area.
        // If thinning destroys a connection, reject the output instead
        // of presenting broken glyphs as safe embroidery.
        if (outlines.contextualShapingPreserved) {
            require(silhouette.coverage >= .36f && silhouette.precision >= .66f) {
                "Os traços da fonte importada não foram reconstruídos com " +
                    "cobertura suficiente. Matriz não liberada para bordado."
            }
        }
        val last = points.last()
        points.add(last.copy(command = StitchCommand.END))
        val coords = points.filter { it.command != StitchCommand.END }
        val bounds = EmbroideryBounds(
            minXUnits = coords.minOf { it.xUnits },
            maxXUnits = coords.maxOf { it.xUnits },
            minYUnits = coords.minOf { it.yUnits },
            maxYUnits = coords.maxOf { it.yUnits }
        )
        val design = EmbroideryDesign(
            fileName = "$filePrefix-" +
                text.lowercase(Locale.ROOT).replace(Regex("[^a-z0-9_-]"), "-") +
                "." + format.lowercase(Locale.ROOT),
            format = format,
            label = text,
            points = points,
            bounds = bounds,
            stitchCount = points.count { it.command == StitchCommand.STITCH },
            jumpCount = points.count { it.command == StitchCommand.JUMP },
            colorChanges = 0,
            endFound = true,
            sourceBytes = ByteArray(0),
            threadColors = listOf(options.color),
            sourceYAxisDown = true,
            isModified = true,
            hoopProfile = options.hoopProfile,
            fabricProfile = options.fabricProfile
        )
        EmbroideryStressPolicy.requireGeneratedSafe(design)
        if (options.enforceHoop && options.hoopProfile != null) {
            require(HoopValidator.validate(design, options.hoopProfile).fits) {
                "O bordado ultrapassa o bastidor selecionado."
            }
        }
        design
    }

    /**
     * Preenchimento adaptativo de contornos para escrita cursiva complexa.
     *
     * A máscara é obtida dos MESMOS contornos vetoriais e usa a regra de
     * winding: contraformas de 'a', 'e', 'o' e voltas permanecem vazadas.
     * Traços são repartidos em passadas curtas <= 3,5 mm, sem alinhar
     * seções transversais a um esqueleto ramificado em cruzamentos.
     *
     * Em vez de afirmar Satin perfeito para todo TTF, esta rota
     * conservadora mantém a aparência e não costura através de vazados.
     */
    /**
     * Stable left-to-right route for connected cursive lettering.
     *
     * A whole connected word can contain two long, overlapping satin bands.
     * Finishing one band from x=0 to x=600 and subsequently starting another
     * at x=0 sends the needle backwards across half of the name.
     *
     * Reorder only when there is a large reversal. Divide the existing satin
     * rails into short X windows; keep their exact geometry, direction, and
     * coverage. Distinct fragments still use explicit JUMP commands, so a
     * return never stitches through the hollow portions of a letter.
     */
    internal fun orderContextualTracks(
        tracks: List<List<Rail>>,
        maxBacktrackUnits: Float = 80f
    ): List<List<Rail>> {
        require(maxBacktrackUnits.isFinite() && maxBacktrackUnits >= 20f)
        val original = tracks.filter { it.isNotEmpty() }.sortedWith(
            compareBy<List<Rail>> { it.first().middle.x }
                .thenBy { it.first().middle.y }
        )
        if (original.size < 2) return original
        // Preserve existing stitch-out exactly when no significant reversal
        // can happen: avoids extra jumps in simple single-stroke glyphs.
        val largeReversal = original.zipWithNext().any { (before, after) ->
            before.last().middle.x - after.first().middle.x > maxBacktrackUnits
        }
        if (!largeReversal) return original

        val minX = original.minOf { path -> path.first().middle.x }
        data class Fragment(val window: Int, val rails: List<Rail>)
        val fragments = mutableListOf<Fragment>()
        original.forEach { route ->
            var window = Int.MIN_VALUE
            var rows = mutableListOf<Rail>()
            fun flush() {
                if (rows.isNotEmpty()) {
                    fragments += Fragment(window, rows.toList())
                    rows = mutableListOf()
                }
            }
            route.forEach { rail ->
                val nextWindow = kotlin.math.floor(
                    ((rail.middle.x - minX) / maxBacktrackUnits).toDouble()
                ).toInt()
                if (nextWindow != window) {
                    flush()
                    window = nextWindow
                }
                rows += rail
            }
            flush()
        }
        return fragments.sortedWith(
            compareBy<Fragment> { it.window }
                .thenBy { it.rails.first().middle.x }
                .thenBy { it.rails.first().middle.y }
        ).map { it.rails }
    }

    /**
     * Exact intersections with the vector outline at a vertical satin rail.
     * A bitmap cell only establishes connectivity; the needle must land on
     * the TrueType/OTF outline, not on the rounded edge of that bitmap cell.
     * Non-zero winding retains a/o/e counters and intentional spaces.
     */
    internal fun vectorSpansAtX(contours: List<List<V>>, x: Float): List<Pair<Float, Float>> {
        val crossings = ArrayList<Pair<Float, Int>>()
        for (ring in contours) {
            if (ring.size < 3) continue
            for (i in ring.indices) {
                val a = ring[i]
                val b = ring[(i + 1) % ring.size]
                if ((a.x <= x && b.x > x) || (b.x <= x && a.x > x)) {
                    val y = a.y + (x - a.x) * (b.y - a.y) / (b.x - a.x)
                    if (y.isFinite()) crossings += y to if (b.x > a.x) 1 else -1
                }
            }
        }
        crossings.sortBy { it.first }
        var winding = 0
        val spans = ArrayList<Pair<Float, Float>>()
        for (i in 0 until crossings.lastIndex) {
            winding += crossings[i].second
            if (winding != 0 && crossings[i + 1].first > crossings[i].first + 0.01f) {
                val low = crossings[i].first
                val high = crossings[i + 1].first
                val previous = spans.lastOrNull()
                if (previous != null && low <= previous.second + 0.02f) {
                    spans[spans.lastIndex] = previous.first to high
                } else {
                    spans += low to high
                }
            }
        }
        return spans
    }

    internal fun planContextualFill(
        contours: List<List<V>>,
        densityMm: Float
    ): PlannedGlyph {
        require(densityMm in 0.3f..1.2f)
        val raster = rasterize(contours, densityMm)
        val colPitch = max(1, (densityMm * 10f / raster.step).roundToInt())
        // Vertical satin bars, not horizontal running stitches. Continuous
        // columns progress in reading order from left to right.
        // Keep the bars <= 6 mm; wider filled regions are split safely.
        val maxBarUnits = 60f
        val active = mutableListOf<MutableList<Rail>>()
        val completed = mutableListOf<List<Rail>>()
        data class Section(
            val top: Int, val bottom: Int, val railTop: Float, val railBottom: Float
        )
        var oldRanges = emptyList<Section>()

        fun endTracks() {
            active.forEach { if (it.isNotEmpty()) completed += it.toList() }
            active.clear()
            oldRanges = emptyList()
        }
        for (x in 1 until raster.width - 1 step colPitch) {
            val atX = raster.left + x * raster.step
            val vectorSpans = vectorSpansAtX(contours, atX)
            val next = ArrayList<Section>()
            var y = 1
            while (y < raster.height - 1) {
                if (!raster.inside(x, y)) { y++; continue }
                val top = y
                while (y < raster.height - 1 && raster.inside(x, y)) y++
                val bottom = y - 1
                if (bottom < top) continue
                val maskTop = raster.top + (top - 0.3f) * raster.step
                val maskBottom = raster.top + (bottom + 0.3f) * raster.step
                // Multiple outline spans in the same raster band indicate
                // a real narrow counter. Never close it with one long rail.
                val touching = vectorSpans.filter { (low, high) ->
                    high >= maskTop - raster.step &&
                        low <= maskBottom + raster.step
                }
                val exact = touching.singleOrNull()
                val railTop = exact?.first ?: maskTop
                val railBottom = exact?.second ?: maskBottom
                val sectionLength = (railBottom - railTop).coerceAtLeast(0f)
                val pieces = max(1, ceil(sectionLength / maxBarUnits).toInt())
                for (piece in 0 until pieces) {
                    val a = top + ((bottom - top + 1) * piece) / pieces
                    val b = top + ((bottom - top + 1) * (piece + 1)) /
                        pieces - 1
                    if (a <= b) {
                        next += Section(
                            a, b,
                            railTop + sectionLength * piece / pieces,
                            railTop + sectionLength * (piece + 1) / pieces
                        )
                    }
                }
            }
            // Spans in consecutive columns belong to one satin track only
            // if their vertical intervals overlap. Otherwise the needle
            // repositions with a JUMP, never stitches through empty lettering.
            val matchedOld = HashSet<Int>()
            val future = mutableListOf<MutableList<Rail>>()
            next.forEach { section ->
                val midY = (section.top + section.bottom) / 2f
                val match = oldRanges.indices.asSequence()
                    .filter { it !in matchedOld }
                    .filter {
                        oldRanges[it].top <= section.bottom &&
                            oldRanges[it].bottom >= section.top
                    }
                    .minByOrNull {
                        kotlin.math.abs((oldRanges[it].top +
                            oldRanges[it].bottom) / 2f - midY)
                    }
                val track = if (match == null) {
                    mutableListOf<Rail>()
                } else {
                    matchedOld += match
                    active[match]
                }
                val yTop = section.railTop
                val yBottom = section.railBottom
                if (yBottom - yTop >= 0.55f) {
                    track += Rail(V(atX, yTop), V(atX, yBottom))
                }
                future += track
            }
            active.forEachIndexed { index, track ->
                if (index !in matchedOld && track.isNotEmpty())
                    completed += track.toList()
            }
            active.clear()
            active.addAll(future)
            oldRanges = next
        }
        endTracks()
        // Short, bounded returns between overlapping satin bands instead of
        // a long rewind to the beginning of an unfinished cursive word.
        val filtered = orderContextualTracks(completed)
        return PlannedGlyph(
            rails = filtered,
            sampledEdges = filtered.sumOf { it.size },
            duplicateRailsDiscarded = 0
        )
    }

    /**
     * Smooth the LOCAL route tangent before laying each perpendicular satin bar.
     *
     * Skeleton pixels move between diagonal and orthogonal steps at sharp
     * cursive joins. The old 1-sample chord rotated adjacent bars by 45-90
     * degrees, leaving triangular holes visible in Bertilda's M/a/r.
     *
     * A bounded arc-length window reduces raster stair-step noise without
     * averaging across a whole letter or losing narrow curves. Only centreline
     * direction changes: actual needle endpoints are still snapped to the
     * original vector outline by exactVectorRail().
     */
    internal fun satinNormalAlongRoute(route: List<V>, index: Int): V? {
        if (route.size < 2 || index !in route.indices) return null
        val radius = 3
        val first = (index - radius).coerceAtLeast(0)
        val last = (index + radius).coerceAtMost(route.lastIndex)
        // Weighted local least-squares direction. The signed weights keep
        // the normal stable in the presence of 1-pixel skeleton jitter.
        val origin = route[index]
        var dx = 0f
        var dy = 0f
        var totalWeight = 0f
        for (j in first..last) {
            if (j == index) continue
            val delta = (j - index).toFloat()
            val weight = 1f / (1f + kotlin.math.abs(delta) * 0.55f)
            dx += (route[j].x - origin.x) * delta * weight
            dy += (route[j].y - origin.y) * delta * weight
            totalWeight += delta * delta * weight
        }
        val tangent = if (totalWeight > 0f) normalized(V(dx, dy)) else null
        if (tangent != null) return V(-tangent.y, tangent.x)
        val previous = route[(index - 1).coerceAtLeast(0)]
        val next = route[(index + 1).coerceAtMost(route.lastIndex)]
        return normalized(V(next.x - previous.x, next.y - previous.y))
            ?.let { V(-it.y, it.x) }
    }

    /**
     * Cap isolated, geometrically implausible Satin width spikes at cursive
     * intersections. At a medial-axis junction, a transverse ray can touch a
     * neighbouring stroke and create a wide rectangular slab (seen in the
     * Bertilda M). Real thick strokes cover several consecutive rails and
     * retain their natural width because the local median is also wide.
     *
     * This never adds rails, crosses gaps, changes their centres or direction,
     * and does not join paths. Original letter coverage is validated after
     * generation by ImportedFontCoverageGuard.
     */
    internal fun smoothIsolatedSatinWidthSpikes(
        rows: List<Rail?>,
        windowRadius: Int = 4
    ): List<Rail?> {
        require(windowRadius in 2..8)
        if (rows.size < windowRadius * 2 + 1) return rows
        fun span(rail: Rail) = length(rail.a, rail.b)
        return rows.mapIndexed { index, rail ->
            if (rail == null) return@mapIndexed null
            // Do not look across missing sections: they represent actual
            // counters or disconnects in the original font.
            val contiguous = mutableListOf<Float>()
            var start = index
            while (start > 0 && index - start < windowRadius && rows[start - 1] != null) {
                start--
            }
            var end = index
            while (end < rows.lastIndex && end - index < windowRadius && rows[end + 1] != null) {
                end++
            }
            for (j in start..end) {
                rows[j]?.let { contiguous += span(it) }
            }
            if (contiguous.size < 5) return@mapIndexed rail
            contiguous.sort()
            val median = contiguous[contiguous.size / 2]
            val current = span(rail)
            // 8 units = 0.8 mm: smaller changes should remain untouched.
            val cap = max(14f, median * 1.85f)
            if (current <= cap + 8f) return@mapIndexed rail
            val centre = rail.middle
            val fraction = cap / current
            Rail(
                V(centre.x + (rail.a.x - centre.x) * fraction,
                    centre.y + (rail.a.y - centre.y) * fraction),
                V(centre.x + (rail.b.x - centre.x) * fraction,
                    centre.y + (rail.b.y - centre.y) * fraction)
            )
        }
    }

    internal fun planContours(
        contours: List<List<V>>,
        densityMm: Float,
        pullMm: Float = 0.2f
    ): PlannedGlyph {
        require(densityMm in 0.3f..1.2f)
        val raster = rasterize(contours, densityMm)
        val skeleton = thin(raster)
        val skeletonPixels = skeleton.count { it }
        // A máscara de uma linha diagonal de 1–2 pixels pode sofrer
        // erosão quase completa no thinning Zhang-Suen. Reconstruir a
        // linha central SOMENTE nesse caso; glifos complexos, curvas
        // largas e demais sequências continuam no percurso aprovado.
        val restoredHairline = if (contours.size == 1) {
            recoverCollapsedThinStroke(raster, skeletonPixels)
        } else null
        if (skeletonPixels < 1 && restoredHairline == null) {
            return PlannedGlyph(emptyList(), 0, 0)
        }
        val routes = if (restoredHairline != null) {
            listOf(restoredHairline)
        } else traceEdges(raster, skeleton)
        val pitch = densityMm * 10f
        val claimed = HashMap<Pair<Int, Int>, MutableList<Rail>>()
        // Hairline strokes of an imported script font may be less than
        // 0.3 mm wide in a small hoop. Do not classify adjacent, visibly
        // distinct transverse bars as already-covered rails.
        val tolerance = (pitch * 0.16f).coerceIn(0.35f, 0.75f)
        fun cell(v: V) =
            floor(v.x / (tolerance * 2.4f)).toInt() to
                floor(v.y / (tolerance * 2.4f)).toInt()
        fun sameRail(a: Rail, b: Rail): Boolean =
            length(a.middle, b.middle) <= tolerance &&
                (
                    (length(a.a, b.a) <= tolerance && length(a.b, b.b) <= tolerance) ||
                    (length(a.a, b.b) <= tolerance && length(a.b, b.a) <= tolerance)
                )
        fun seen(rail: Rail): Boolean {
            val (cx, cy) = cell(rail.middle)
            for (dx in -1..1) for (dy in -1..1) {
                if (claimed[cx + dx to cy + dy].orEmpty().any { sameRail(it, rail) }) {
                    return true
                }
            }
            claimed.getOrPut(cell(rail.middle)) { mutableListOf() }.add(rail)
            return false
        }
        val result = mutableListOf<List<Rail>>()
        var duplicates = 0
        // Planejamento determinístico por continuidade do traço e não por
        // distância isolada: termina a ramificação corrente antes de trocar
        // para uma área distante que exigiria retorno visual.
        val orderedRoutes = orderSkeletonRoutes(routes, raster.step)
        orderedRoutes.forEach { route ->
            val interpolated = resample(route, pitch)
            var batch = mutableListOf<Rail>()
            fun endBatch() {
                if (batch.isNotEmpty()) result += batch
                batch = mutableListOf()
            }
            val rawRails = interpolated.mapIndexed { i, c ->
                satinNormalAlongRoute(interpolated, i)?.let { normal ->
                    crossSection(raster, c, normal, pullMm * 10f, contours)
                }?.takeIf { length(it.a, it.b) >= 1.5f }
            }
            // Missing one or two columns in an otherwise continuous glyph
            // must not turn the font into a dashed line. Interpolation is
            // allowed ONLY where the original filled font mask remains solid.
            // A rasterização pode eliminar espaços vetoriais estreitos
            // entre curvas. Antes de interpolar uma barra ausente, exigir
            // continuidade na geometria REAL TTF/OTF (sem cruzar vazados).
            val filledRails = repairShortRailGaps(
                rawRails, interpolated, raster.step,
                uninterruptedVector = { from, to ->
                    rasterRailStaysInsideOutline(contours, from, to)
                }
            ) { v ->
                insideOriginalVector(contours, v)
            }
            // Suppress isolated cross-branch Satin slabs while keeping
            // sustained thick calligraphic downstrokes unchanged.
            smoothIsolatedSatinWidthSpikes(filledRails).forEach { row ->
                if (row == null) {
                    endBatch()
                } else if (seen(row)) {
                    duplicates++
                    endBatch()
                } else {
                    batch.add(row)
                }
            }
            endBatch()
        }
        // Disconnected dot components of imported fonts can collapse to a
        // single skeleton pixel. Such a pixel creates only one Satin bar and
        // turns the dot into a thin dash. Refill only these small, *detached*
        // upper accents, keeping all other glyph paths and needle routing.
        val restoredDots = buildDetachedDotRails(raster, densityMm, pullMm)
        if (restoredDots.isNotEmpty()) {
            result.removeAll { path ->
                val middle = path.firstOrNull()?.middle
                middle != null && restoredDots.any { dot ->
                    middle.x in dot.left..dot.right &&
                        middle.y in dot.top..dot.bottom
                }
            }
            // Um pingo superior é finalizado ANTES de descer a haste:
            // nunca voltar para o topo depois de concluir a letra.
            result.addAll(0, restoredDots.map { it.rails })
        }
        return PlannedGlyph(result, orderedRoutes.sumOf { it.size }, duplicates)
    }

    /**
     * Fill at most two missing Satin rails along one existing skeleton route.
     * Never synthesize a connection through empty font pixels, between routes
     * or between glyphs; the simulation's stitching order stays unchanged.
     */
    internal fun repairShortRailGaps(
        rows: List<Rail?>,
        route: List<V>,
        gridStep: Float,
        // Exact vector segment verification, not a few raster sample points.
        // Default preserves the simple geometry-only unit-test contract.
        uninterruptedVector: (V, V) -> Boolean = { _, _ -> true },
        insideOriginalOutline: (V) -> Boolean
    ): List<Rail?> {
        if (rows.size != route.size || rows.size < 3) return rows
        val repaired = rows.toMutableList()
        var i = 1
        while (i < rows.lastIndex) {
            if (rows[i] != null) { i++; continue }
            val start = i
            while (i < rows.lastIndex && rows[i] == null) i++
            val gapLength = i - start
            if (gapLength !in 1..2 || i >= rows.size) continue
            val before = rows[start - 1] ?: continue
            val after = rows[i] ?: continue
            if (length(before.middle, after.middle) >
                (gapLength + 1) * gridStep * 7.5f) continue
            // A centre-to-centre chord may cross a tiny counter or a real
            // break between script strokes even if every raster sample says
            // "filled". That break must remain a JUMP, not a satin bridge.
            if (!uninterruptedVector(before.middle, after.middle)) continue

            // Do not bridge across real holes/counters in the letter:
            // both the missing medial positions and the intermediate
            // straight segments must fall inside the existing font shape.
            val covered = (start..i).all { n ->
                if (!insideOriginalOutline(route[n])) false
                else {
                    val a = route[n - 1]
                    val b = route[n]
                    insideOriginalOutline(
                        V((a.x + b.x) * 0.5f, (a.y + b.y) * 0.5f)
                    )
                }
            }
            if (!covered) continue
            for (j in 0 until gapLength) {
                val factor = (j + 1f) / (gapLength + 1f)
                fun mix(a: V, b: V) = V(
                    a.x + (b.x - a.x) * factor,
                    a.y + (b.y - a.y) * factor
                )
                repaired[start + j] = Rail(mix(before.a, after.a), mix(before.b, after.b))
            }
        }
        return repaired
    }

    internal fun orderSkeletonRoutes(
        routes: List<List<V>>,
        gridStep: Float
    ): List<List<V>> {
        val pending = routes.filter { it.size >= 2 }.toMutableList()
        if (pending.isEmpty()) return emptyList()
        val ordered = mutableListOf<List<V>>()
        var previousEnd: V? = null
        var previousDirection: V? = null
        val joinTolerance = max(2f, gridStep * 1.8f)

        while (pending.isNotEmpty()) {
            var bestIndex = 0
            var bestReversed = false
            var bestScore = Float.POSITIVE_INFINITY
            for (i in pending.indices) {
                val segment = pending[i]
                for (reversed in listOf(false, true)) {
                    val entry = if (reversed) segment.last() else segment.first()
                    val exit = if (reversed) segment.first() else segment.last()
                    val score = if (previousEnd == null) {
                        // Começar pela extremidade esquerda mais baixa.
                        entry.x * 3f - entry.y * 0.08f
                    } else {
                        val gap = length(previousEnd, entry)
                        if (gap <= joinTolerance) {
                            val next = if (reversed) segment[segment.lastIndex - 1]
                                else segment[1]
                            val direction = normalized(V(next.x - entry.x, next.y - entry.y))
                            val alignment = if (previousDirection != null &&
                                direction != null) {
                                (previousDirection.x * direction.x +
                                    previousDirection.y * direction.y).coerceIn(-1f, 1f)
                            } else 0f
                            // Preferir seguir reto no mesmo ramo do esqueleto.
                            gap * 2f + (1f - alignment) * joinTolerance * 3f
                        } else {
                            // Um salto separa ramos desconectados. Visitar
                            // primeiro o que resta à esquerda, sem costurar
                            // linhas de ligação ou regressos longos.
                            val back = max(0f, previousEnd.x - entry.x)
                            10000f + entry.x * 2f + gap * 0.5f + back * 3f
                        }
                    }
                    if (score < bestScore) {
                        bestScore = score
                        bestIndex = i
                        bestReversed = reversed
                    }
                }
            }
            val selected = pending.removeAt(bestIndex)
            val oriented = if (bestReversed) selected.asReversed() else selected
            ordered += oriented
            previousEnd = oriented.last()
            val last = oriented[oriented.lastIndex - 1]
            previousDirection = normalized(V(previousEnd.x - last.x, previousEnd.y - last.y))
        }
        return ordered
    }

    private data class DotRails(
        val left: Float,
        val top: Float,
        val right: Float,
        val bottom: Float,
        val rails: List<Rail>
    )

    private data class FilledIsland(
        val minX: Int,
        val minY: Int,
        val maxX: Int,
        val maxY: Int,
        val pixelCount: Int
    )

    /**
     * Restore tiny, detached upper marks (e.g. the dot above i or j) using
     * real horizontal Satin rails sampled from their existing font outlines.
     * It does not draw a synthetic circle or interfere with the main glyph.
     */
    private fun buildDetachedDotRails(
        raster: Raster,
        densityMm: Float,
        pullMm: Float
    ): List<DotRails> {
        val visited = BooleanArray(raster.mask.size)
        val islands = mutableListOf<FilledIsland>()
        for (seed in raster.mask.indices) {
            if (!raster.mask[seed] || visited[seed]) continue
            val queue = java.util.ArrayDeque<Int>()
            queue.add(seed)
            visited[seed] = true
            var count = 0
            var minX = raster.width
            var minY = raster.height
            var maxX = 0
            var maxY = 0
            while (!queue.isEmpty()) {
                val pixel = queue.removeFirst()
                val x = pixel % raster.width
                val y = pixel / raster.width
                count++
                minX = minOf(minX, x)
                maxX = maxOf(maxX, x)
                minY = minOf(minY, y)
                maxY = maxOf(maxY, y)
                for (dy in -1..1) for (dx in -1..1) {
                    if (dx == 0 && dy == 0) continue
                    val nx = x + dx
                    val ny = y + dy
                    if (nx !in 0 until raster.width ||
                        ny !in 0 until raster.height) continue
                    val next = raster.index(nx, ny)
                    if (raster.mask[next] && !visited[next]) {
                        visited[next] = true
                        queue.add(next)
                    }
                }
            }
            islands += FilledIsland(minX, minY, maxX, maxY, count)
        }
        val body = islands.maxByOrNull { it.pixelCount } ?: return emptyList()
        val bodyHeight = (body.maxY - body.minY + 1) * raster.step
        if (bodyHeight < 10f) return emptyList()
        val rowPitch = max(1, (densityMm * 10f / raster.step).roundToInt())
        return islands.asSequence()
            .filter { island ->
                if (island === body || island.maxY >= body.minY) return@filter false
                val w = (island.maxX - island.minX + 1) * raster.step
                val h = (island.maxY - island.minY + 1) * raster.step
                val ratio = w / h
                w <= minOf(55f, bodyHeight * 0.48f) &&
                    h <= minOf(55f, bodyHeight * 0.48f) &&
                    ratio in 0.45f..2.2f &&
                    island.pixelCount * 4 < body.pixelCount
            }
            .sortedBy { it.minX }
            .mapNotNull { island ->
                val filledRows = (island.minY..island.maxY).filter { y ->
                    (island.minX..island.maxX).any { x -> raster.inside(x, y) }
                }
                if (filledRows.isEmpty()) return@mapNotNull null
                val selected = filledRows.filterIndexed { index, _ ->
                    index % rowPitch == 0
                }.toMutableSet()
                if (selected.size < 3 && filledRows.size >= 3) {
                    selected += filledRows.first()
                    selected += filledRows[filledRows.size / 2]
                    selected += filledRows.last()
                }
                val pullUnits = pullMm * 10f
                val rails = selected.sorted().mapNotNull { y ->
                    val occupied = (island.minX..island.maxX)
                        .filter { x -> raster.inside(x, y) }
                    if (occupied.isEmpty()) return@mapNotNull null
                    // Every bar follows the original mask width at this row.
                    val left = raster.left + occupied.first() * raster.step
                    val right = raster.left + occupied.last() * raster.step
                    val atY = raster.top + y * raster.step
                    Rail(
                        V(left - raster.step * 0.45f - pullUnits, atY),
                        V(right + raster.step * 0.45f + pullUnits, atY)
                    )
                }
                if (rails.isEmpty()) return@mapNotNull null
                DotRails(
                    raster.left + (island.minX - 1) * raster.step,
                    raster.top + (island.minY - 1) * raster.step,
                    raster.left + (island.maxX + 1) * raster.step,
                    raster.top + (island.maxY + 1) * raster.step,
                    rails
                )
            }
            .toList()
    }

    /**
     * Only rescue an extremely slender, single-contour line if the thinning
     * phase destroyed almost all its medial axis. No changes to the order of
     * ordinary satin branches or to the simulator.
     */
    private fun recoverCollapsedThinStroke(
        raster: Raster,
        skeletonPixels: Int
    ): List<V>? {
        var minX = raster.width
        var maxX = -1
        var minY = raster.height
        var maxY = -1
        var pixels = 0
        for (y in 1 until raster.height - 1) {
            for (x in 1 until raster.width - 1) {
                if (!raster.inside(x, y)) continue
                pixels++
                minX = minOf(minX, x)
                maxX = maxOf(maxX, x)
                minY = minOf(minY, y)
                maxY = maxOf(maxY, y)
            }
        }
        if (pixels == 0) return null
        val spanX = maxX - minX + 1
        val spanY = maxY - minY + 1
        val majorSpan = max(spanX, spanY)
        if (majorSpan < 15 ||
            pixels > majorSpan * 3.2f ||
            skeletonPixels >= majorSpan * 0.35f) return null

        // The raster is a skinny ribbon. Its row/column midpoint follows
        // the ORIGINAL font geometry, not an invented straight line.
        return if (spanY >= spanX) {
            (minY..maxY).mapNotNull { y ->
                var occupied = 0
                var sumX = 0f
                for (x in minX..maxX) if (raster.inside(x, y)) {
                    occupied++
                    sumX += x
                }
                if (occupied == 0) null else V(
                    raster.left + (sumX / occupied) * raster.step,
                    raster.top + y * raster.step
                )
            }.takeIf { it.size >= 8 }
        } else {
            (minX..maxX).mapNotNull { x ->
                var occupied = 0
                var sumY = 0f
                for (y in minY..maxY) if (raster.inside(x, y)) {
                    occupied++
                    sumY += y
                }
                if (occupied == 0) null else V(
                    raster.left + x * raster.step,
                    raster.top + (sumY / occupied) * raster.step
                )
            }.takeIf { it.size >= 8 }
        }
    }

    private fun rasterize(contours: List<List<V>>, densityMm: Float): Raster {
        val points = contours.flatten()
        require(points.isNotEmpty()) { "Fonte sem contorno." }
        val minX = points.minOf { it.x }
        val maxX = points.maxOf { it.x }
        val minY = points.minOf { it.y }
        val maxY = points.maxOf { it.y }
        // No bastidor pequeno os detalhes cursivos podem ter menos de
        // 0,25 mm: evitar que a amostragem grosseira quebre o contorno.
        var step = max(0.75f, densityMm * 10f * 0.26f)
        var width = ceil((maxX - minX) / step).toInt() + 5
        var height = ceil((maxY - minY) / step).toInt() + 5
        while (width.toLong() * height.toLong() > 350_000) {
            step *= 1.2f
            width = ceil((maxX - minX) / step).toInt() + 5
            height = ceil((maxY - minY) / step).toInt() + 5
        }
        val left = minX - step * 2
        val top = minY - step * 2
        val mask = BooleanArray(width * height)
        // Conservative subpixel scan conversion: sample the centre and two
        // nearby Y positions within each pixel row. A very narrow cursive
        // stroke must not disappear just because it misses a grid centre.
        // Keep the TrueType non-zero winding rule and the original contours;
        // no closing/dilation is applied to large areas or letter counters.
        fun fillRow(pixelY: Int, sampleY: Float) {
            val intersections = mutableListOf<Pair<Float, Int>>()
            contours.forEach { polygon ->
                if (polygon.size < 3) return@forEach
                polygon.indices.forEach { i ->
                    val a = polygon[i]
                    val b = polygon[(i + 1) % polygon.size]
                    if ((a.y <= sampleY && b.y > sampleY) ||
                        (b.y <= sampleY && a.y > sampleY)) {
                        val x = a.x +
                            (sampleY - a.y) * (b.x - a.x) / (b.y - a.y)
                        intersections += x to (if (b.y > a.y) 1 else -1)
                    }
                }
            }
            intersections.sortBy { it.first }
            var winding = 0
            for (i in 0 until intersections.lastIndex) {
                winding += intersections[i].second
                if (winding == 0) continue
                val leftX = intersections[i].first
                val rightX = intersections[i + 1].first
                val from = max(1, ceil((leftX - left) / step).toInt())
                val to = minOf(width - 2, floor((rightX - left) / step).toInt())
                if (from <= to) {
                    for (x in from..to) mask[pixelY * width + x] = true
                } else if (rightX > leftX) {
                    // Preserve a genuine filled interval thinner than one
                    // raster cell. Crucial at the tips of M/a/r/i.
                    val nearest = (((leftX + rightX) * 0.5f - left) / step)
                        .roundToInt().coerceIn(1, width - 2)
                    mask[pixelY * width + nearest] = true
                }
            }
        }
        for (y in 1 until height - 1) {
            val rowY = top + y * step
            fillRow(y, rowY)
            fillRow(y, rowY - step * 0.30f)
            fillRow(y, rowY + step * 0.30f)
        }
        return Raster(width, height, step, left, top, mask)
    }

    // Zhang-Suen skeletonization: a mask pixel may be deleted only if the
    // local 8-neighborhood remains connected. Boundary crossings are unique.
    private fun thin(raster: Raster): BooleanArray {
        val pixels = raster.mask.copyOf()
        val w = raster.width
        val h = raster.height
        fun on(x: Int, y: Int) = pixels[y * w + x]
        var changed = true
        var pass = 0
        while (changed && pass < 220) {
            changed = false
            for (phase in 0..1) {
                val erase = mutableListOf<Int>()
                for (y in 1 until h - 1) for (x in 1 until w - 1) {
                    if (!on(x, y)) continue
                    val n = booleanArrayOf(
                        on(x, y-1), on(x+1, y-1), on(x+1, y),
                        on(x+1, y+1), on(x, y+1), on(x-1, y+1),
                        on(x-1, y), on(x-1, y-1)
                    )
                    val count = n.count { it }
                    if (count !in 2..6) continue
                    val transitions = n.indices.count { !n[it] && n[(it+1)%8] }
                    if (transitions != 1) continue
                    val p2 = n[0]; val p4 = n[2]; val p6 = n[4]; val p8 = n[6]
                    val condition = if (phase == 0) {
                        !(p2 && p4 && p6) && !(p4 && p6 && p8)
                    } else {
                        !(p2 && p4 && p8) && !(p2 && p6 && p8)
                    }
                    if (condition) erase += y * w + x
                }
                erase.forEach { pixels[it] = false }
                if (erase.isNotEmpty()) changed = true
            }
            pass++
        }
        return pixels
    }

    private fun traceEdges(raster: Raster, skeleton: BooleanArray): List<List<V>> {
        val w = raster.width
        val h = raster.height
        fun neighbors(i: Int): List<Int> {
            val x = i % w; val y = i / w
            val out = mutableListOf<Int>()
            for (dy in -1..1) for (dx in -1..1) {
                if (dx == 0 && dy == 0) continue
                val nx = x + dx; val ny = y + dy
                if (nx !in 0 until w || ny !in 0 until h) continue
                val neighbor = ny * w + nx
                if (!skeleton[neighbor]) continue
                // 4-connected orthogonal alternatives remove diagonal
                // shortcuts that generate loops at 90-degree bends.
                if (dx != 0 && dy != 0 &&
                    (skeleton[y * w + nx] || skeleton[ny * w + x])) continue
                out += neighbor
            }
            return out
        }
        val nodes = skeleton.indices.filter { skeleton[it] }
        val used = HashSet<Edge>()
        val paths = mutableListOf<List<V>>()
        fun walk(source: Int, first: Int) {
            var previous = source
            var current = first
            val track = mutableListOf(source, first)
            used.add(Edge.of(source, first))
            while (true) {
                val available = neighbors(current)
                    .filter { it != previous && Edge.of(it, current) !in used }
                if (available.size != 1) break
                val next = available[0]
                used.add(Edge.of(current, next))
                previous = current
                current = next
                track.add(current)
                if (current == source) break
            }
            if (track.size >= 2) paths += track.map(raster::point)
        }
        // Endpoints / branches first; loops and remaining edges second.
        val ordered = nodes.sortedWith(compareBy<Int> {
            if (neighbors(it).size == 2) 1 else 0
        }.thenBy { it % w })
        ordered.forEach { node ->
            neighbors(node).forEach { next ->
                if (Edge.of(node, next) !in used) walk(node, next)
            }
        }
        // Pontos e ilhas pequenos (como o pingo do i) afinam ate
        // um unico pixel e nao possuem arestas. Eles tambem precisam
        // gerar preenchimento, sem serem descartados.
        nodes.filter { neighbors(it).isEmpty() }.forEach { lone ->
            val p = raster.point(lone)
            val half = raster.step * 0.60f
            paths += listOf(
                V(p.x, p.y - half),
                p,
                V(p.x, p.y + half)
            )
        }
        return paths
    }

    private fun resample(path: List<V>, pitch: Float): List<V> {
        if (path.size < 2) return path
        val lengths = path.zipWithNext().map { (a,b) -> length(a,b) }
        val total = lengths.sum()
        if (total < pitch * 0.55f) return path
        val count = max(2, (total / pitch).roundToInt() + 1)
        val samples = mutableListOf<V>()
        var seg = 0
        var before = 0f
        for (i in 0 until count) {
            val d = total * i / (count - 1)
            while (seg < lengths.lastIndex && before + lengths[seg] < d) {
                before += lengths[seg]
                seg++
            }
            val fraction = if (lengths[seg] <= 0f) 0f else
                ((d - before) / lengths[seg]).coerceIn(0f,1f)
            val a = path[seg]
            val b = path[seg+1]
            samples += V(
                a.x + (b.x - a.x) * fraction,
                a.y + (b.y - a.y) * fraction
            )
        }
        return samples
    }

    /**
     * Refine transverse Satin endpoints against the exact TTF/OTF contours.
     * The skeleton still defines stitch ORDER, but the bitmap cannot decide
     * needle endpoints: its stair-step boundaries are visible as jagged glyphs.
     *
     * Intersect each half-ray with the first outline boundary. This preserves
     * counters (a/o), disconnected ornaments, and narrow joins. A ray cannot
     * continue beyond the nearest contour or a 3.5 mm half-width limit.
     */
    /**
     * Avoid pulling a satin bar across the adjoining branch of a cursive
     * letter. At a junction the medial-axis skeleton may sit very near
     * one outline edge yet the opposite ray reaches an unrelated stroke,
     * creating rectangular slabs on Bertilda's M, r and a.
     *
     * Preserve normal, center, pitch and the real outline intersections.
     * Bound only extreme asymmetry, never insert a stitch across a counter.
     */
    internal fun constrainCrossStrokeExtents(
        negativeExtent: Float,
        positiveExtent: Float,
        maxSideRatio: Float = 2.5f
    ): Pair<Float, Float> {
        require(negativeExtent.isFinite() && positiveExtent.isFinite() &&
            negativeExtent > 0f && positiveExtent > 0f &&
            maxSideRatio >= 2f)
        val shorter = minOf(negativeExtent, positiveExtent)
        val longer = shorter * maxSideRatio
        return minOf(negativeExtent, longer) to minOf(positiveExtent, longer)
    }

    internal fun exactVectorRail(
        contours: List<List<V>>, center: V, normal: V, pullUnits: Float
    ): Rail? {
        var winding = 0
        val origin = center
        var left = Float.POSITIVE_INFINITY
        var right = Float.POSITIVE_INFINITY
        for (ring in contours) {
            if (ring.size < 3) continue
            for (i in ring.indices) {
                val a = ring[i]
                val b = ring[(i + 1) % ring.size]
                val ex = b.x - a.x
                val ey = b.y - a.y
                // Non-zero winding: reject centres inside a genuine letter
                // counter, even when a raster sampling pixel is occupied.
                val side = ex * (origin.y - a.y) - ey * (origin.x - a.x)
                if (a.y <= origin.y && b.y > origin.y && side > 0f) winding++
                if (a.y > origin.y && b.y <= origin.y && side < 0f) winding--
                val det = normal.x * ey - normal.y * ex
                if (kotlin.math.abs(det) < 1e-5f) continue
                val px = a.x - origin.x
                val py = a.y - origin.y
                val t = (px * ey - py * ex) / det
                val u = (px * normal.y - py * normal.x) / det
                if (u < 0f || u >= 1f) continue
                if (t > 0.01f && t < right) right = t
                if (t < -0.01f && -t < left) left = -t
            }
        }
        if (winding == 0 || !left.isFinite() || !right.isFinite()) return null
        // Wide genuine outlines need a bounded Satin bar, not a missing bar.
        // Endpoints are still clamped to the 6 mm machine safety envelope.
        // A large left/right mismatch at a cursive junction is evidence
        // the ray has crossed into another branch of the font outline.
        val (limitedLeft, limitedRight) = constrainCrossStrokeExtents(left, right)
        val lengthScale = minOf(1f, 60f / (limitedLeft + limitedRight))
        val safeLeft = limitedLeft * lengthScale
        val safeRight = limitedRight * lengthScale
        val width = safeLeft + safeRight
        // Real 0.05–0.15 mm hairlines of imported cursive fonts must survive.
        // Pull compensation remains proportional to the actual vector width.
        if (width < 0.4f) return null
        // 6mm maximum bar length including compensation: the physical
        // embroidery machine must never sew the full 7mm search radius.
        val safePull = minOf(
            pullUnits,
            max(0.4f, width * 0.5f),
            max(0f, (60f - width) * 0.5f)
        )
        return Rail(
            V(origin.x - normal.x * (safeLeft + safePull),
                origin.y - normal.y * (safeLeft + safePull)),
            V(origin.x + normal.x * (safeRight + safePull),
                origin.y + normal.y * (safeRight + safePull))
        )
    }

    /**
     * A raster mask is only an approximation of the original TTF shape.
     * Any emergency raster Satin rail must remain entirely inside the
     * original non-zero-winding vector fill. In particular, it must not
     * bridge the counter in an 'a' or a disconnected cursive flourish.
     */
    internal fun insideOriginalVector(
        contours: List<List<V>>,
        point: V
    ): Boolean {
        var winding = 0
        for (ring in contours) {
            for (i in ring.indices) {
                val a = ring[i]
                val b = ring[(i + 1) % ring.size]
                val side = (b.x - a.x) * (point.y - a.y) -
                    (b.y - a.y) * (point.x - a.x)
                if (a.y <= point.y && b.y > point.y && side > 0f) winding++
                if (a.y > point.y && b.y <= point.y && side < 0f) winding--
            }
        }
        return winding != 0
    }

    internal fun rasterRailStaysInsideOutline(
        contours: List<List<V>>, a: V, b: V
    ): Boolean {
        val length = length(a, b)
        if (length < 0.45f || length > 60f ||
            !length.isFinite()) return false
        // Check raw (pre-pull) geometry; legitimate pull compensation can
        // extend slightly outside. A handful of samples alone cannot detect
        // a small counter/gap between them, so also reject ANY intersection
        // with the original outline in the interior of this Satin chord.
        val dx = b.x - a.x
        val dy = b.y - a.y
        for (ring in contours) {
            for (i in ring.indices) {
                val p = ring[i]
                val q = ring[(i + 1) % ring.size]
                val ex = q.x - p.x
                val ey = q.y - p.y
                val determinant = dx * ey - dy * ex
                if (abs(determinant) < 1e-6f) continue
                val px = p.x - a.x
                val py = p.y - a.y
                val t = (px * ey - py * ex) / determinant
                val u = (px * dy - py * dx) / determinant
                if (t > 0.001f && t < 0.999f &&
                    u >= 0f && u < 1f) return false
            }
        }
        return listOf(.1f, .25f, .5f, .75f, .9f).all { t ->
            insideOriginalVector(contours,
                V(a.x + dx * t, a.y + dy * t))
        }
    }

    /**
     * Sub-pixel centering strictly ACROSS the local stroke. Rasterization
     * rounds a narrow hairline to a grid cell that can lie just outside the
     * source outline. No search along the glyph or into another rail.
     */
    internal fun snapRasterCenterToVector(
        contours: List<List<V>>,
        center: V,
        normal: V,
        rasterStep: Float
    ): V? {
        require(rasterStep > 0f && rasterStep.isFinite())
        val norm = normalized(normal) ?: return null
        // A point exactly ON the outline can satisfy winding but have no
        // transverse intersection on one side. Require a real vector bar
        // before accepting the raster sample as a valid Satin centre.
        fun usable(v: V) =
            insideOriginalVector(contours, v) &&
                exactVectorRail(contours, v, norm, 0f) != null
        if (usable(center)) return center
        val quantum = rasterStep * 0.16f
        for (n in 1..5) {
            for (sign in listOf(-1f, 1f)) {
                val candidate = V(
                    center.x + norm.x * quantum * n * sign,
                    center.y + norm.y * quantum * n * sign
                )
                if (usable(candidate)) return candidate
            }
        }
        return null
    }

    private fun crossSection(
        mask: Raster, center: V, normal: V, pullUnits: Float,
        contours: List<List<V>>
    ): Rail? {
        val sampling = minOf(0.85f, mask.step / 2f)
        fun insideAt(x: Float, y: Float): Boolean {
            val xi = ((x - mask.left) / mask.step).roundToInt()
            val yi = ((y - mask.top) / mask.step).roundToInt()
            return mask.inside(xi, yi)
        }
        val effectiveCenter = if (insideAt(center.x, center.y)) {
            center
        } else {
            // Chord interpolation at a sharp bend can fall just outside a
            // narrow glyph. Snap at most one mask pixel, never bridge holes.
            val cx = ((center.x - mask.left) / mask.step).roundToInt()
            val cy = ((center.y - mask.top) / mask.step).roundToInt()
            val nearest = (-1..1).flatMap { dy ->
                (-1..1).map { dx -> cx + dx to cy + dy }
            }.filter { (x, y) -> mask.inside(x, y) }
                .minByOrNull { (x, y) ->
                    val px = mask.left + x * mask.step
                    val py = mask.top + y * mask.step
                    length(center, V(px, py))
                } ?: return null
            V(mask.left + nearest.first * mask.step,
                mask.top + nearest.second * mask.step)
        }
        // A legitimately thin TTF stroke may occupy a raster cell whose
        // centre falls just OUTSIDE its sub-pixel vector boundary. Resolve
        // the centre against the real vector before intersecting endpoints;
        // never accept a disconnected raster-only rail.
        val vectorCenter = snapRasterCenterToVector(
            contours, effectiveCenter, normal, mask.step
        )
        if (vectorCenter != null) {
            exactVectorRail(contours, vectorCenter, normal, pullUnits)?.let {
                return it
            }
        }
        val maxExtent = 35f // 7 mm full satin width limit
        fun edge(sign: Float): Float {
            var d = 0f
            while (d <= maxExtent &&
                insideAt(
                    effectiveCenter.x + normal.x * d * sign,
                    effectiveCenter.y + normal.y * d * sign
                )) d += sampling
            // A última célula ocupada representa uma área finita, não
            // um ponto sem largura. Metade da célula evita perder a
            // cobertura em hastes cursivas de um único pixel.
            return (d - sampling).coerceAtLeast(mask.step * 0.5f)
        }
        val a = edge(-1f)
        val b = edge(1f)
        val originalWidth = a + b
        if (originalWidth < mask.step * 0.45f) return null
        // Never trust a connected raster band until it is proved to be
        // connected in the original vector shape too.
        val rawA = V(effectiveCenter.x - normal.x * a,
            effectiveCenter.y - normal.y * a)
        val rawB = V(effectiveCenter.x + normal.x * b,
            effectiveCenter.y + normal.y * b)
        if (!rasterRailStaysInsideOutline(contours, rawA, rawB)) return null
        // Preserve thin *real* strokes, but never generate overlong bars
        // from a quantized mask when the exact TTF rail was rejected.
        val safePull = minOf(pullUnits, max(0.4f, originalWidth * 0.5f),
            max(0f, (60f - originalWidth) * 0.5f))
        val scale = minOf(1f, 60f / (originalWidth + 2f * safePull))
        return Rail(
            V(effectiveCenter.x - normal.x * (a + safePull) * scale,
                effectiveCenter.y - normal.y * (a + safePull) * scale),
            V(effectiveCenter.x + normal.x * (b + safePull) * scale,
                effectiveCenter.y + normal.y * (b + safePull) * scale)
        )
    }

    internal fun stitchPlannedGlyphForTest(
        planned: PlannedGlyph,
        underlay: SatinUnderlayMode = SatinUnderlayMode.NONE
    ): List<EmbroideryPoint> {
        val points = mutableListOf<EmbroideryPoint>()
        Stitcher(points).sewGlyph(planned.rails, underlay)
        return points
    }

    private class Stitcher(val points: MutableList<EmbroideryPoint>) {
        private var needle: V? = null
        private fun command(p: V, cmd: StitchCommand) {
            val x = p.x.roundToInt()
            val y = p.y.roundToInt()
            val last = points.lastOrNull()
            if (last != null &&
                last.xUnits == x && last.yUnits == y &&
                last.command == cmd) return
            require(points.size < EmbroideryStressPolicy.MAX_GENERATED_COMMANDS) {
                "A fonte gerou pontos demais; tente menor altura ou outro estilo."
            }
            points += EmbroideryPoint(x, y, cmd, 0)
            needle = p
        }
        private fun jump(p: V) {
            val start = needle
            if (start != null && length(start, p) < 0.5f) return
            command(p, StitchCommand.JUMP)
        }
        private fun sew(p: V) {
            val start = needle
            if (start == null) { jump(p); return }
            val distance = length(start, p)
            if (distance < 0.45f) return
            val chunks = max(1, ceil(distance / 70f).toInt())
            for (k in 1..chunks) {
                val t = k.toFloat() / chunks
                command(V(start.x+(p.x-start.x)*t, start.y+(p.y-start.y)*t),
                    StitchCommand.STITCH)
            }
        }
        fun sewGlyph(
            paths: List<List<Rail>>,
            underlay: SatinUnderlayMode,
            forceJumpBetweenPaths: Boolean = false
        ) {
            var anchored = false
            paths.forEach { rows ->
                if (rows.isEmpty()) return@forEach
                // Orientação já calculada pelo planejador de traços.
                // Não inverter um ramo novamente por proximidade física.
                val begin = rows.first().middle
                val doUnderlay = underlay != SatinUnderlayMode.NONE && rows.size >= 6
                if (doUnderlay) {
                    jump(begin)
                    // One center run, then satin in reverse without
                    // retracing the center back to the start.
                    for (index in rows.indices step 5) sew(rows[index].middle)
                    sew(rows.last().middle)
                }
                val cover = if (doUnderlay) rows.asReversed() else rows
                val entry = cover.first().a
                val lastPos = needle
                // Caminhos distintos de fonte cursiva não devem criar
                // costura de ligação nem quando as bordas quase se tocam.
                if (forceJumpBetweenPaths || lastPos == null ||
                    length(lastPos, entry) > 4f
                ) jump(entry) else sew(entry)
                if (!anchored) {
                    // One short tie-in for this glyph, not every medial branch.
                    val r = cover.first()
                    val t = V(r.a.x + (r.b.x-r.a.x)*0.08f,
                        r.a.y + (r.b.y-r.a.y)*0.08f)
                    sew(t)
                    sew(r.a)
                    anchored = true
                }
                // A bordadeira deve alternar o sentido de cada barra
                // Satin. Costurar sempre a -> b força uma DIAGONAL longa
                // de b(n) para a(n+1) a cada coluna, criando justamente
                // o emaranhado visível no nome "Maria" em fonte cursiva.
                cover.forEachIndexed { index, rail ->
                    val entry = if (index % 2 == 0) rail.a else rail.b
                    val exit = if (index % 2 == 0) rail.b else rail.a
                    val position = needle
                    if (position == null || length(position, entry) > 8f) {
                        // Nunca criar uma costura de ligação através de
                        // vazados ou entre partes desconectadas.
                        jump(entry)
                    } else {
                        sew(entry)
                    }
                    sew(exit)
                }
            }
            // There are deliberately NO per-path tie-off round trips.
            // The machine-facing finishing policy handles last tie/trim.
        }
    }

    private fun length(a: V, b: V) =
        hypot((b.x-a.x).toDouble(), (b.y-a.y).toDouble()).toFloat()
    private fun normalized(v: V): V? {
        val n = hypot(v.x.toDouble(), v.y.toDouble()).toFloat()
        return if (n < 0.0001f) null else V(v.x/n, v.y/n)
    }
